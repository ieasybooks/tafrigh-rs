//! Generate reference docs from `tafrigh spec` without a separate Usage installation.

use std::io::{self, Read};
use std::path::PathBuf;

use usage_parser::docs::manpage::ManpageRenderer;
use usage_parser::docs::markdown::MarkdownRenderer;

fn main() -> anyhow::Result<()> {
    let destination = std::env::args_os()
        .nth(1)
        .map_or_else(|| PathBuf::from("docs"), PathBuf::from);
    let mut kdl = String::new();
    io::stdin().read_to_string(&mut kdl)?;
    let mut spec: usage_parser::Spec = kdl.parse()?;
    // Reference pages describe the interface; the installed binary supplies its version.
    spec.version = None;
    let markdown = MarkdownRenderer::new(spec.clone()).render_spec()?;
    let manpage = ManpageRenderer::new(spec).render()?;
    std::fs::create_dir_all(&destination)?;
    std::fs::write(
        destination.join("cli.md"),
        format!(
            "<!-- Generated by sh scripts/cli-docs.sh; do not edit directly. -->\n\n{markdown}\n"
        ),
    )?;
    std::fs::write(
        destination.join("tafrigh.1"),
        format!(".\\\" Generated by sh scripts/cli-docs.sh; do not edit directly.\n{manpage}"),
    )?;
    Ok(())
}
