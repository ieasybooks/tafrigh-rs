#!/bin/sh
# Run from the repository root after `mise install usage`.
set -eu

if ! command -v usage >/dev/null 2>&1; then
    echo "Install the pinned Usage CLI with 'mise install usage' before generating docs." >&2
    exit 1
fi

destination=${1:-docs}
work_dir=$(mktemp -d)
trap 'rm -rf "$work_dir"' EXIT HUP INT TERM

cargo run --quiet --locked --package tafrigh-cli --bin tafrigh -- spec > "$work_dir/spec.kdl"
# Reference pages describe the interface; release version bumps should not change them.
sed '/^version /d' "$work_dir/spec.kdl" > "$work_dir/reference.kdl"

mkdir -p "$destination"
usage generate markdown --html-encode --file "$work_dir/reference.kdl" --out-file "$destination/cli.md"
{
    printf '%s\n' '.\" Generated by sh scripts/cli-docs.sh; do not edit directly.'
    usage generate manpage --file "$work_dir/reference.kdl"
} > "$destination/tafrigh.1"
